"""한글 입력 상태로 친 글자를 실제로 누른 영문 키로 되돌린다 (두벌식 표준 자판).

macOS 터미널은 한글 입력 상태에서 비밀번호를 한글 그대로 받는다("ㅁㅇ" ← a, d 키).
브라우저 비밀번호 칸은 영문으로만 입력되므로 둘이 어긋난다. 자판은 키→글자가 1:1이라
조합된 글자를 풀면 누른 키 순서가 그대로 나온다.

한계: 한글 상태에서 Shift는 쌍자음(ㄲㄸㅃㅆㅉ)·ㅒㅖ에만 쓰인다. 그 밖의 키는 Shift를 눌러도
같은 글자가 나와 **대문자였는지 알 수 없다** — 소문자로 되돌린다.
"""

_KEY = {
    "ㄱ": "r", "ㄲ": "R", "ㄴ": "s", "ㄷ": "e", "ㄸ": "E", "ㄹ": "f", "ㅁ": "a", "ㅂ": "q", "ㅃ": "Q",
    "ㅅ": "t", "ㅆ": "T", "ㅇ": "d", "ㅈ": "w", "ㅉ": "W", "ㅊ": "c", "ㅋ": "z", "ㅌ": "x", "ㅍ": "v",
    "ㅎ": "g",
    "ㅏ": "k", "ㅐ": "o", "ㅑ": "i", "ㅒ": "O", "ㅓ": "j", "ㅔ": "p", "ㅕ": "u", "ㅖ": "P", "ㅗ": "h",
    "ㅘ": "hk", "ㅙ": "ho", "ㅚ": "hl", "ㅛ": "y", "ㅜ": "n", "ㅝ": "nj", "ㅞ": "np", "ㅟ": "nl",
    "ㅠ": "b", "ㅡ": "m", "ㅢ": "ml", "ㅣ": "l",
    "ㄳ": "rt", "ㄵ": "sw", "ㄶ": "sg", "ㄺ": "fr", "ㄻ": "fa", "ㄼ": "fq", "ㄽ": "ft", "ㄾ": "fx",
    "ㄿ": "fv", "ㅀ": "fg", "ㅄ": "qt",
}
_CHO = "ㄱㄲㄴㄷㄸㄹㅁㅂㅃㅅㅆㅇㅈㅉㅊㅋㅌㅍㅎ"
_JUNG = "ㅏㅐㅑㅒㅓㅔㅕㅖㅗㅘㅙㅚㅛㅜㅝㅞㅟㅠㅡㅢㅣ"
_JONG = ["", *"ㄱㄲㄳㄴㄵㄶㄷㄹㄺㄻㄼㄽㄾㄿㅀㅁㅂㅄㅅㅆㅇㅈㅊㅋㅌㅍㅎ"]


def has_hangul(s: str) -> bool:
    return any("가" <= c <= "힣" or c in _KEY for c in s)


def to_keys(s: str) -> str:
    """한글 글자를 두벌식 영문 키로 바꾼다. 한글이 아닌 글자는 그대로 둔다."""
    out = []
    for c in s:
        if "가" <= c <= "힣":
            n = ord(c) - 0xAC00
            out.append(_KEY[_CHO[n // 588]] + _KEY[_JUNG[n % 588 // 28]])
            jong = _JONG[n % 28]
            if jong:
                out.append(_KEY[jong])
        else:
            out.append(_KEY.get(c, c))
    return "".join(out)
